public class ApiExceptionHandlerTests
{
    private const string InternalDetail = "Connection refused (internal-bar.svc.cluster.local:8443)";

    private static async Task<(bool Handled, int StatusCode, ProblemDetails? ProblemDetails)> HandleAsync(
        Exception exception,
        ILogger<ApiExceptionHandler>? logger = null,
        bool exposeUpstreamExceptionMessages = false,
        string environmentName = "Production")
    {
        ProblemDetails? captured = null;
        var problemDetailsService = new Mock<IProblemDetailsService>();
        problemDetailsService
            .Setup(s => s.TryWriteAsync(It.IsAny<ProblemDetailsContext>()))
            .Callback<ProblemDetailsContext>(context => captured = context.ProblemDetails)
            .ReturnsAsync(true);

        var handler = new ApiExceptionHandler(problemDetailsService.Object,
            Options.Create(new ExceptionHandlingOptions
            {
                ExposeUpstreamExceptionMessages = exposeUpstreamExceptionMessages
            }),
            Environment(environmentName),
            logger ?? NullLogger<ApiExceptionHandler>.Instance);
        var httpContext = new DefaultHttpContext();

        var handled = await handler.TryHandleAsync(httpContext, exception, TestContext.Current.CancellationToken);

        return (handled, httpContext.Response.StatusCode, captured);
    }

    private static IHostEnvironment Environment(string name)
    {
        var environment = new Mock<IHostEnvironment>();
        environment.SetupGet(e => e.EnvironmentName).Returns(name);
        return environment.Object;
    }

    public static TheoryData<Exception> UpstreamFailures => new()
    {
        new FooConnectorException(new HttpRequestException(InternalDetail))
        {
            IsHandled = true,
            CouldBeTransient = true,
            CouldBeExternallySolvable = true
        },
        new BarConnectorException(new HttpRequestException(InternalDetail))
        {
            IsHandled = true,
            CouldBeTransient = true,
            CouldBeExternallySolvable = true
        },
        new ApiClientEventsException(new InvalidOperationException(InternalDetail))
        {
            IsHandled = false,
            CouldBeTransient = true
        }
    };

    [Fact]
    public async Task TryHandleAsync_ClientFacingException_IsNotLoggedAsUpstreamFailure()
    {
        var logger = new CapturingLogger();

        await HandleAsync(new BadRequestException("Name is required"), logger);

        Assert.Empty(logger.Entries);
    }

    [Fact]
    public async Task TryHandleAsync_DoesNotHandleUnknownExceptions()
    {
        ProblemDetails? captured = null;
        var problemDetailsService = new Mock<IProblemDetailsService>();
        problemDetailsService
            .Setup(s => s.TryWriteAsync(It.IsAny<ProblemDetailsContext>()))
            .Callback<ProblemDetailsContext>(context => captured = context.ProblemDetails)
            .ReturnsAsync(true);

        var handler = new ApiExceptionHandler(problemDetailsService.Object,
            Options.Create(new ExceptionHandlingOptions()), Environment("Production"),
            NullLogger<ApiExceptionHandler>.Instance);
        var httpContext = new DefaultHttpContext();

        var handled = await handler.TryHandleAsync(httpContext, new InvalidOperationException("boom"),
            TestContext.Current.CancellationToken);

        Assert.False(handled);
        Assert.Null(captured);
        problemDetailsService.Verify(s => s.TryWriteAsync(It.IsAny<ProblemDetailsContext>()), Times.Never);
    }

    [Fact]
    public async Task TryHandleAsync_MapsBadRequestException_To400ProblemDetails()
    {
        var written = await HandleAsync(new BadRequestException("Name is required"));

        Assert.True(written.Handled);
        Assert.Equal(StatusCodes.Status400BadRequest, written.StatusCode);
        Assert.Equal("Bad Request", written.ProblemDetails?.Title);
        Assert.Equal("Name is required", written.ProblemDetails?.Detail);
        Assert.Equal(StatusCodes.Status400BadRequest, written.ProblemDetails?.Status);
    }

    [Fact]
    public async Task TryHandleAsync_MapsConflictException_To409ProblemDetails()
    {
        var written = await HandleAsync(new ConflictException("Resource is locked"));

        Assert.True(written.Handled);
        Assert.Equal(StatusCodes.Status409Conflict, written.StatusCode);
        Assert.Equal("Conflict", written.ProblemDetails?.Title);
        Assert.Equal("Resource is locked", written.ProblemDetails?.Detail);
        Assert.Equal(StatusCodes.Status409Conflict, written.ProblemDetails?.Status);
    }

    [Fact]
    public async Task TryHandleAsync_MapsNoChangesToModifyException_To304ProblemDetails()
    {
        var written = await HandleAsync(new NoChangesToModifyException());

        Assert.True(written.Handled);
        Assert.Equal(StatusCodes.Status304NotModified, written.StatusCode);
        Assert.Equal("Not Modified", written.ProblemDetails?.Title);
        Assert.Null(written.ProblemDetails?.Detail);
        Assert.Equal(StatusCodes.Status304NotModified, written.ProblemDetails?.Status);
    }

    [Fact]
    public async Task TryHandleAsync_MapsRequestTooLargeException_To413ProblemDetails()
    {
        var written =
