    private const string TableName = "example-items";

    private static DynamoExampleItemRepository CreateRepository(
        IAmazonDynamoDB? client = null,
        IDynamoDBContext? context = null)
    {
        return new DynamoExampleItemRepository(
            client ?? new Mock<IAmazonDynamoDB>().Object,
            context ?? new Mock<IDynamoDBContext>().Object,
            Options.Create(new DynamoExampleItemRepository.ConfigurationModel
