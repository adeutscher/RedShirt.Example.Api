    [Fact]
    public async Task DeleteByName_DoesNotDelete_WhenItemIsMissing()
    {
        var context = new Mock<IDynamoDBContext>();
        context
            .Setup(c => c.LoadAsync<ExampleItemMapping>(
                It.IsAny<object>(),
                It.IsAny<LoadConfig>(),
                It.IsAny<CancellationToken>()))
            .Returns(Task.FromResult<ExampleItemMapping?>(null)!);
        var repository = CreateRepository(context: context.Object);

        await Assert.ThrowsAsync<ResourceNotFoundException>(() =>
            repository.DeleteByName("missing", TestContext.Current.CancellationToken));

        context.Verify(c => c.DeleteAsync(
            It.IsAny<ExampleItemModel>(),
            It.IsAny<DeleteConfig>(),
            It.IsAny<CancellationToken>()), Times.Never);
    }

    [Fact]
    public async Task DeleteByName_LoadsThenDeletes_WhenItemExists()
    {
        var context = new Mock<IDynamoDBContext>();
