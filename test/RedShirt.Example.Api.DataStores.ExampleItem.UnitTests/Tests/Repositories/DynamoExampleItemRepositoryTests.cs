    [Fact]
    public async Task GetListAsync_MapsItemsAndEncodesContinuationToken()
    {
        var client = new Mock<IAmazonDynamoDB>();
        var context = new Mock<IDynamoDBContext>();
        var lastKey = new Dictionary<string, AttributeValue>
        {
            ["Name"] = new() {S = "next"}
        };
        client
            .Setup(c => c.ScanAsync(It.IsAny<ScanRequest>(), It.IsAny<CancellationToken>()))
            .ReturnsAsync(new ScanResponse
            {
                Items =
                [
                    new Dictionary<string, AttributeValue>
                    {
                        ["Name"] = new() {S = "widget"}
                    }
                ],
                LastEvaluatedKey = lastKey
            });
        context
            .Setup(c => c.FromDocument<ExampleItemModel>(It.IsAny<Document>()))
            .Returns(new ExampleItemModel {Name = "widget"});
        var repository = CreateRepository(client.Object, context.Object);

        var result = await repository.GetListAsync(null, TestContext.Current.CancellationToken);

        Assert.Single(result.Items);
        Assert.Equal("widget", result.Items[0].Name);
        Assert.Equal(
            Convert.ToBase64String(JsonSerializer.SerializeToUtf8Bytes(lastKey)),
            result.ContinuationToken);
        context.Verify(c => c.FromDocument<ExampleItemModel>(It.IsAny<Document>()), Times.Once);
    }

    [Fact]
    public async Task GetListAsync_PassesDecodedExclusiveStartKey_WhenContinuationTokenIsProvided()
    {
        var startKey = new Dictionary<string, AttributeValue>
        {
            ["Name"] = new() {S = "cursor"}
        };
        var continuationToken = Convert.ToBase64String(JsonSerializer.SerializeToUtf8Bytes(startKey));
        var client = new Mock<IAmazonDynamoDB>();
        var context = new Mock<IDynamoDBContext>();
        ScanRequest? capturedRequest = null;
        client
            .Setup(c => c.ScanAsync(It.IsAny<ScanRequest>(), It.IsAny<CancellationToken>()))
            .Callback<ScanRequest, CancellationToken>((request, _) => capturedRequest = request)
            .ReturnsAsync(new ScanResponse
            {
                Items = [],
                LastEvaluatedKey = new Dictionary<string, AttributeValue>()
            });
        var repository = CreateRepository(client.Object, context.Object);

        var result = await repository.GetListAsync(continuationToken, TestContext.Current.CancellationToken);

        Assert.Null(result.ContinuationToken);
        Assert.NotNull(capturedRequest);
        Assert.NotNull(capturedRequest.ExclusiveStartKey);
        Assert.Equal("cursor", capturedRequest.ExclusiveStartKey["Name"].S);
    }

